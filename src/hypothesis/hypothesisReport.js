/**
 * Hypothesis report formatting (browser). Evaluation itself runs on the server.
 */

export const ACTIVE_HYPOTHESIS_KEY = "targetforge_active_hypothesis_v1";

/**
 * Generate formatted Markdown / text report for export
 */
export function generateHypothesisReport(evaluation) {
  if (!evaluation) return "";
  const { parsed, decisionScore, scientificVerdict, causalityScore, contradictionEngine, evidenceMatrix, experiments, falsificationCriteria, competingHypotheses, aiDebate } = evaluation;

  const dateStr = new Date().toISOString().split("T")[0];

  return `# TargetForge Scientific Hypothesis Report
**Date:** ${dateStr}
**Evaluation Engine:** TargetForge Scientific Hypothesis Evaluator

---

## 1. Primary Hypothesis
**Target:** ${parsed.target} (${parsed.targetGene || "N/A"})
**Disease Indication:** ${parsed.disease}
**Intervention:** ${parsed.intervention}
**Proposed Mechanism:** ${parsed.proposedMechanism}
**Expected Outcome:** ${parsed.expectedOutcome}
**Potential Risks:** ${parsed.potentialRisks}
**Patient Population:** ${parsed.patientPopulation || "General indicated population"}

---

## 2. TargetForge Evidence-Based Hypothesis Score
**Overall Score:** ${decisionScore?.overall}/100 — **${decisionScore?.classification}**
*(Note: ${decisionScore?.note})*

### Component Breakdown
- **Biological Plausibility:** ${decisionScore?.breakdown?.biologicalPlausibility}/100
- **Human Evidence (Genetics/Clinical):** ${decisionScore?.breakdown?.humanEvidence}/100
- **Causal Evidence:** ${decisionScore?.breakdown?.causalEvidence}/100
- **Pharmacological Feasibility:** ${decisionScore?.breakdown?.pharmacologicalFeasibility}/100
- **Clinical Validation:** ${decisionScore?.breakdown?.clinicalValidation}/100
- **Safety / Tolerability:** ${decisionScore?.breakdown?.safety}/100
- **Contradictory Penalty:** ${decisionScore?.breakdown?.contradictoryPenalty} pts

---

## 3. Scientific Verdict & Recommendation
**Verdict:** ${scientificVerdict?.verdict}
**Recommendation:** **${scientificVerdict?.recommendation}**
**Rationale:** ${scientificVerdict?.recommendationRationale}

---

## 4. Causality Assessment
**Status:** **${causalityScore?.classification}** (Score: ${causalityScore?.score}/100)
**Core Principle:** CORRELATION ≠ CAUSATION
**Reasoning:** ${causalityScore?.reasoning}

---

## 5. Why This Hypothesis Might Be Wrong (Contradiction Engine)
${(contradictionEngine?.whyMightBeWrong || [])
  .map(
    (c, i) =>
      `### 5.${i + 1} ${c.point}\n${c.detail}\n*Source:* ${c.source}\n`
  )
  .join("\n")}

---

## 6. What Would Prove Us Wrong? (Falsification Criteria)
${(falsificationCriteria || [])
  .map((crit, i) => `${i + 1}. ${crit}`)
  .join("\n")}

---

## 7. Recommended Experimental Protocols
${(experiments || [])
  .map(
    (exp, i) => `### Experiment ${i + 1}: ${exp.name}
- **Objective:** ${exp.objective}
- **Model System:** ${exp.model}
- **Intervention:** ${exp.intervention}
- **Control:** ${exp.control}
- **Primary Endpoint:** ${exp.primaryEndpoint}
- **Secondary Endpoint:** ${exp.secondaryEndpoint}
- **IF Hypothesis is TRUE:** ${exp.expectedTrue}
- **IF Hypothesis is FALSE:** ${exp.expectedFalse}
- **Interpretation:** ${exp.interpretation}
`
  )
  .join("\n")}

---

## 8. Evidence Matrix
| Evidence Claim | Type | Direction | Strength | Human Relevance | Source Citation |
| --- | --- | --- | --- | --- | --- |
${(evidenceMatrix || [])
  .map(
    (row) =>
      `| ${row.claim.replace(/\|/g, "/")} | ${row.evidence_type} | ${row.direction} | ${row.strength} | ${row.human_relevance} | ${row.source} |`
  )
  .join("\n")}

---

## 9. Competing / Alternative Hypotheses
${(competingHypotheses || [])
  .map(
    (alt, i) => `### Alternative ${i + 1}: ${alt.hypothesis}
- **Supporting Evidence:** ${alt.evidence}
- **Contradictions / Gaps:** ${alt.contradictions}
- **Confidence Level:** ${alt.confidence}
`
  )
  .join("\n")}

---

## 10. AI Scientific Expert Panel Debate
${(aiDebate || [])
  .map(
    (deb) => `**${deb.title} (${deb.role}):**
${deb.argument}
`
  )
  .join("\n")}

---
*Report generated by TargetForge Drug Discovery Platform. For research hypothesis evaluation only.*
`;
}
